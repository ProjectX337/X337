import os


class ProjectGenerator:


    def __init__(self):

        self.base_path = (
            "workspace/projects"
        )



    # ---------------------------------
    # Generate Project
    # ---------------------------------

    def generate(
        self,
        project_name,
        task,
        plan=None
    ):


        project_path = os.path.join(

            self.base_path,

            project_name

        )


        os.makedirs(

            project_path,

            exist_ok=True

        )



        architecture = self.analyze_task(

            task.title

        )



        files = self.create_architecture(

            architecture,

            plan

        )



        generated_files = []



        for filename, content in files.items():


            filepath = os.path.join(

                project_path,

                filename

            )


            directory = os.path.dirname(

                filepath

            )


            if directory:


                os.makedirs(

                    directory,

                    exist_ok=True

                )



            with open(

                filepath,

                "w"

            ) as file:


                file.write(

                    content

                )



            generated_files.append(

                filepath

            )



        return {


            "project": project_name,


            "architecture": architecture,


            "plan": plan,


            "files": generated_files,


            "path": project_path

        }





    # ---------------------------------
    # Detect Architecture
    # ---------------------------------

    def analyze_task(
        self,
        title
    ):


        title = title.lower()



        if "api" in title:

            return "fastapi"



        if "website" in title:

            return "website"



        if "agent" in title:

            return "ai_agent"



        return "python"





    # ---------------------------------
    # Blueprint Router
    # ---------------------------------

    def create_architecture(
        self,
        architecture,
        plan=None
    ):



        if architecture == "fastapi":

            return self.fastapi_project(
                plan
            )



        if architecture == "website":

            return self.website_project()



        if architecture == "ai_agent":

            return self.agent_project()



        return self.python_project()





